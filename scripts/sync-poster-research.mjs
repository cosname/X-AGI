import { createHash } from 'node:crypto';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { parseCsv } from './sync-tencent-program.mjs';

const DEFAULT_OUTPUT = fileURLToPath(new URL('../src/data/poster-research.generated.ts', import.meta.url));
const CURATION_PATH = fileURLToPath(new URL('../src/data/poster-research-curation.json', import.meta.url));
const PUBLIC_HEADERS = ['门票类型', '姓名', '学校/单位', '海报标题（需要和论文标题一致）', '您的文章线上地址'];
const hash = (value) => createHash('sha256').update(value).digest('hex');
const normalized = (value) => value.normalize('NFKC').replace(/\s+/gu, ' ').trim();

export const posterSubmissionKey = (name, title, url) => hash(JSON.stringify([name, title, url].map(normalized)));

function publicPaperUrl(value) {
  const url = new URL(value);
  const hostname = url.hostname.replace(/\.$/, '');
  if (url.protocol !== 'https:' || url.username || url.password
    || /(?:^|\.)(?:bagevent\.com|localhost)$/.test(hostname)
    || /^(?:\[|\d+(?:\.\d+){3}$)/.test(hostname)
    || !hostname.includes('.')) {
    throw new Error(`Not a public paper URL: ${url.origin}`);
  }
  return url.href;
}

export function parsePosterResearchCsv(csv, curation) {
  const [headers = [], ...rows] = parseCsv(csv);
  for (const header of [...PUBLIC_HEADERS, '审核状态']) {
    if (headers.filter((value) => value === header).length !== 1) throw new Error(`Missing or duplicated poster column: ${header}`);
  }
  if (curation.schemaVersion !== 1 || !Array.isArray(curation.entries) || !Array.isArray(curation.exclusions)) {
    throw new Error('Unsupported poster curation schema.');
  }
  const byKey = new Map();
  for (const entry of curation.entries) {
    if (byKey.has(entry.sourceKey)) throw new Error('Duplicate source key in poster curation.');
    byKey.set(entry.sourceKey, entry);
  }
  const exclusions = new Map(curation.exclusions.map((entry) => [entry.sourceKey, entry.reason]));
  const papers = [];
  const paperById = new Map();
  const sourceRecords = [];
  let excludedCount = 0;
  let mergedCount = 0;
  for (const row of rows.filter((row) => row.some((value) => value.trim()))) {
    const cell = (header) => (row[headers.indexOf(header)] ?? '').trim();
    if (cell('门票类型') !== 'Rising Stars Poster') throw new Error('Poster import requires a Poster-only registration export.');
    const name = cell('姓名');
    const title = cell('海报标题（需要和论文标题一致）');
    const submittedUrl = cell('您的文章线上地址');
    const sourceKey = posterSubmissionKey(name, title, submittedUrl);
    if (exclusions.has(sourceKey)) {
      if (!exclusions.get(sourceKey)) throw new Error('Poster exclusions require a reason.');
      excludedCount += 1;
      continue;
    }
    if (cell('审核状态') !== '审核通过') throw new Error(`Registration review needs confirmation for ${name}.`);
    const reviewed = byKey.get(sourceKey);
    if (!reviewed) throw new Error(`Unreviewed poster submission: ${name} / ${title}`);
    if (!/^poster-[a-z0-9-]+$/.test(reviewed.id) || !reviewed.title?.trim() || !reviewed.venue?.trim()
      || !reviewed.evidence?.length || !['primary-source', 'submitted-pdf'].includes(reviewed.verification)) {
      throw new Error(`Incomplete poster curation for ${name}.`);
    }
    if (!name || !cell('学校/单位')) throw new Error('Poster applicant name and affiliation are required.');
    const paper = {
      id: reviewed.id,
      title: reviewed.title,
      applicantName: name,
      affiliation: reviewed.affiliation?.trim() || cell('学校/单位'),
      venue: reviewed.venue,
      href: publicPaperUrl(reviewed.href),
    };
    sourceRecords.push({ name, affiliation: paper.affiliation, submittedTitle: title, submittedUrl });
    const previous = paperById.get(paper.id);
    if (previous) {
      if (previous.applicantName !== paper.applicantName || previous.title !== paper.title || previous.href !== paper.href) {
        throw new Error(`Poster identity collision: ${paper.id}`);
      }
      // The first supplied registration is retained; alternative affiliations are not combined by guesswork.
      mergedCount += 1;
      continue;
    }
    paperById.set(paper.id, paper);
    papers.push(paper);
  }
  if (!papers.length) throw new Error('No reviewed poster papers found.');
  return {
    sourceHash: hash(JSON.stringify(sourceRecords)),
    papers,
    excludedCount,
    mergedCount,
  };
}

export function renderPosterResearchModule({ sourceHash, papers }) {
  return '// Generated by scripts/sync-poster-research.mjs. Do not edit manually.\n\n'
    + 'export type PosterResearchPaper = {\n'
    + '  readonly id: string;\n  readonly title: string;\n  readonly applicantName: string;\n'
    + '  readonly affiliation: string;\n  readonly venue: string;\n  readonly href: string;\n};\n\n'
    + `export const posterResearchSource = ${JSON.stringify({ sourceHash, status: 'registration', papers }, null, 2)} as const;\n\n`
    + 'export const posterResearchPapers: readonly PosterResearchPaper[] = posterResearchSource.papers;\n';
}

async function readWorkbookCsv(file) {
  if (path.extname(file).toLowerCase() === '.csv') return readFile(file, 'utf8');
  const directory = await mkdtemp(path.join(os.tmpdir(), 'xagi-poster-import-'));
  try {
    await promisify(execFile)('soffice', [
      `-env:UserInstallation=${pathToFileURL(path.join(directory, 'profile')).href}`,
      '--headless', '--convert-to', 'csv', '--outdir', directory, file,
    ], { timeout: 60_000 });
    const files = (await readdir(directory)).filter((name) => name.endsWith('.csv'));
    if (files.length !== 1) throw new Error('Expected one converted Poster CSV.');
    return await readFile(path.join(directory, files[0]), 'utf8');
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

export async function syncPosterResearch(input, output = DEFAULT_OUTPUT) {
  const result = parsePosterResearchCsv(await readWorkbookCsv(input), JSON.parse(await readFile(CURATION_PATH, 'utf8')));
  const current = await readFile(output, 'utf8').catch(() => '');
  const previousSource = current.match(/export const posterResearchSource = ([\s\S]+?) as const;/)?.[1];
  if (previousSource && JSON.parse(previousSource).papers.length - result.papers.length > 2) {
    throw new Error('Poster import would remove more than two papers. Confirm the complete source export first.');
  }
  const next = renderPosterResearchModule(result);
  if (current !== next) await writeFile(output, next);
  return { changed: current !== next, paperCount: result.papers.length, excludedCount: result.excludedCount, mergedCount: result.mergedCount };
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  const args = process.argv.slice(2);
  if (args.length !== 2 || !['--workbook', '--csv'].includes(args[0]) || !path.isAbsolute(args[1])) {
    throw new Error('Usage: npm run posters:sync-research -- --workbook <absolute-workbook-path>');
  }
  console.log(JSON.stringify(await syncPosterResearch(args[1])));
}
